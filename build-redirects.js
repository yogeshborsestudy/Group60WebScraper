const fs = require('fs');
const path = require('path');

// Read the BACKEND_URL environment variable from Netlify config.
const backendUrl = process.env.BACKEND_URL;

if (!backendUrl) {
  console.warn('========================================================================');
  console.warn('WARNING: BACKEND_URL environment variable is not defined.');
  console.warn('Requests to /api/* will not be proxied correctly in production.');
  console.warn('Please set BACKEND_URL in your Netlify Site settings (Environment variables).');
  console.warn('e.g., BACKEND_URL = https://your-backend-app.onrender.com');
  console.warn('========================================================================');
} else {
  console.log(`Setting up Netlify API redirect proxy to: ${backendUrl}`);
}

const cleanBackendUrl = backendUrl ? (backendUrl.endsWith('/') ? backendUrl.slice(0, -1) : backendUrl) : 'http://localhost:3000';

// Netlify redirects format:
// 1. Rewrite API requests to the external backend URL (forced redirect with 200 status)
// 2. Rewrite all other routes to index.html for client-side routing support (standard SPA)
let redirectsContent = `# Netlify Redirects File - Automatically generated by build-redirects.js\n`;
redirectsContent += `/api/*  ${cleanBackendUrl}/api/:splat  200!\n`;
redirectsContent += `/*      /index.html  200\n`;

const outputPath = path.join(__dirname, '_redirects');

try {
  fs.writeFileSync(outputPath, redirectsContent);
  console.log(`Successfully generated _redirects pointing to: ${cleanBackendUrl}`);
} catch (error) {
  console.error('Error generating _redirects:', error);
  process.exit(1);
}
